//! Runtime-agnostic record sources.
//!
//! Nothing in this module — or in the crate — knows about tokio. The async
//! trait is declared with native `async fn` in a trait and then *specialised*
//! by [`trait_variant`] into a `Send` flavour:
//!
//! ```text
//! #[trait_variant::make(RecordSource: Send)]
//! pub trait LocalRecordSource { async fn next_record(..) -> ..; }
//! ```
//!
//! `LocalRecordSource` keeps the ergonomic `async fn` signature for
//! single-threaded drivers; the generated `RecordSource` returns
//! `impl Future + Send` instead, which is what a multi-threaded executor
//! needs. Neither spawns anything: a source only *returns* a future, and the
//! caller (the CLI's tokio runtime, a test's hand-rolled poll loop, …) decides
//! when and where to drive it. That is the whole contract.

// An in-memory source has nothing to await, which is why its impl spells out
// the desugared `fn .. -> impl Future` form instead of using `async fn`.

use std::collections::VecDeque;
use std::future::Future;

use crate::error::LibError;
use crate::model::Record;

/// A pull-based stream of records.
///
/// `next_record` returns `Ok(None)` exactly once the source is exhausted.
#[allow(
    async_fn_in_trait,
    reason = "the Send-bounded variant generated by trait_variant is the public, executor-facing API"
)]
#[trait_variant::make(RecordSource: Send)]
pub trait LocalRecordSource {
    /// Yield the next record, or `None` when the source is drained.
    ///
    /// # Errors
    ///
    /// Returns [`LibError`] if the underlying storage fails.
    async fn next_record(&mut self) -> Result<Option<Record>, LibError>;
}

/// A synchronous, in-memory source.
///
/// It is asynchronous on the *outside* only: polling this future never blocks
/// and never performs I/O, which makes it the reference implementation the
/// async machinery is tested against.
#[derive(Debug, Clone, Default)]
pub struct SliceSource {
    records: VecDeque<Record>,
}

impl SliceSource {
    /// Wrap an owned collection of records.
    #[must_use]
    pub fn new(records: impl IntoIterator<Item = Record>) -> Self {
        Self {
            records: records.into_iter().collect(),
        }
    }

    /// How many records are still queued.
    #[must_use]
    pub fn remaining(&self) -> usize {
        self.records.len()
    }
}

impl LocalRecordSource for SliceSource {
    // Deliberately written *without* the `async` keyword: this is exactly what
    // `async fn` in a trait desugars to, and spelling it out keeps the impl
    // honest about returning a ready future the caller still has to poll.
    fn next_record(&mut self) -> impl Future<Output = Result<Option<Record>, LibError>> {
        std::future::ready(Ok(self.records.pop_front()))
    }
}

/// Drain any [`LocalRecordSource`] into a `Vec` on a single thread.
///
/// # Errors
///
/// Propagates whatever the source returns.
pub async fn drain(source: &mut impl LocalRecordSource) -> Result<Vec<Record>, LibError> {
    let mut out = Vec::new();
    while let Some(record) = source.next_record().await? {
        out.push(record);
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use std::future::Future;
    use std::pin::pin;
    use std::task::{Context, Poll, Waker};

    use super::{drain, LocalRecordSource, SliceSource};
    use crate::grammar::parse_line;

    /// The smallest possible executor: this crate must not pull in a runtime,
    /// so tests drive futures with `Waker::noop()`.
    fn block_on<F: Future>(future: F) -> F::Output {
        let waker = Waker::noop();
        let mut cx = Context::from_waker(waker);
        let mut future = pin!(future);
        loop {
            match future.as_mut().poll(&mut cx) {
                Poll::Ready(value) => return value,
                Poll::Pending => std::thread::yield_now(),
            }
        }
    }

    #[test]
    fn drains_in_order() {
        let line = "1700000000000 INFO engine latency_ms=12";
        let record = parse_line(line).expect("valid line");
        let mut source = SliceSource::new(vec![record.clone()]);
        let drained = block_on(drain(&mut source)).expect("no i/o");
        assert_eq!(drained, vec![record]);
        assert_eq!(source.remaining(), 0);
        assert_eq!(block_on(source.next_record()).expect("no i/o"), None);
    }
}
